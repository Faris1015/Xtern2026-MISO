    def _match_hub(self, q_norm: str) -> Optional[str]:
        mapping = {
            "indiana": "INDIANA.HUB",
            "michigan": "MICHIGAN.HUB",
            "illinois": "ILLINOIS.HUB",
            "minn": "MINN.HUB",
            "minnesota": "MINN.HUB",
            "louisiana": "LOUISIANA.HUB",
            "texas": "TEXAS.HUB",
        }
        for k, v in mapping.items():
            if k in q_norm:
                return v
        if "lmp" in q_norm or "price" in q_norm or "hub" in q_norm or "market" in q_norm:
            return "INDIANA.HUB"
        return None

    def _match_glossary(self, q_norm: str) -> Optional[Dict[str, Any]]:
        COMMON_STOPWORDS = {"to", "in", "is", "as", "at", "by", "on", "or", "an", "no", "so", "he", "it", "of", "for", "and", "the"}
        for acronym, entry in self.dm.glossary.items():
            acr_lower = acronym.lower()
            term_lower = entry["term"].lower()

            # If acronym is a common English stopword (e.g. "TO", "IN", "IS", "HE"), only match if explicitly asked or exact
            if acr_lower in COMMON_STOPWORDS:
                is_exact = (
                    q_norm == acr_lower
                    or f"what is {acr_lower}" in q_norm
                    or f"define {acr_lower}" in q_norm
                    or f"explain {acr_lower}" in q_norm
                )
                if is_exact or term_lower in q_norm:
                    return {"acronym": acronym, **entry}
                continue

            # Match whole word or exact acronym in query
            if re.search(r"\b" + re.escape(acr_lower) + r"\b", q_norm) or acr_lower == q_norm:
                return {"acronym": acronym, **entry}
            if term_lower in q_norm:
                return {"acronym": acronym, **entry}
        return None


