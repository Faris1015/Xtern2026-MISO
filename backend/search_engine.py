def normalize(text: str) -> str:
    return re.sub(r"[^\w\s]", "", text.lower()).strip()


class SearchEngine:
    """Intelligent parsing and retrieval engine for MISO OmniSearch."""

    def __init__(self):
        self.dm = data_manager

    def search(self, query: str, persona: str = "Power Trader") -> SearchResponse:
        resp = self._execute_search(query, persona)
        inferred, reason = self._infer_persona(query, persona)
        resp.inferredPersona = inferred
        resp.personaSuggestionReason = reason
        return resp

    def _infer_persona(self, query: str, current_persona: str) -> tuple[Optional[str], Optional[str]]:
        q_lower = query.lower()
        
        trader_keywords = [
            "spread", "arbitrage", "congestion", "mcc", "mlc", "he 18", "he 19", "volatility",
            "basis", "day-ahead", "real-time", "da-rt", "clearing price", "expost", "ex-post",
            "marginal congestion", "marginal loss", "trading", "financial transmission", "da", "rt"
        ]
        coop_keywords = [
            "baseload", "hedging", "reserve margin", "pra", "planning resource auction",
            "co-op", "cooperative", "capacity", "retail", "municipal", "reliability requirement",
            "coop", "rate stability", "procurement", "member load", "lse", "load serving", "wholesale power cost"
        ]
        regulator_keywords = [
            "cone", "ferc", "tariff", "lrtp", "compliance", "interstate", "jurisdiction",
            "cost of new entry", "prpm", "filing", "cost allocation", "audit", "reliability imperative",
            "order 888", "order 2023", "ratepayer", "prudence", "market monitoring", "imm", "resource adequacy"
        ]
        public_keywords = [
            "what is", "clean energy", "carbon", "solar", "wind peak", "why", "green",
            "blackout", "outage", "record", "renewable", "how much", "simple", "tell me about",
            "who is miso", "manitoba", "canada", "explain", "basics", "beginner", "carbon-free", "emissions"
        ]

        def count_matches(keywords: list[str]) -> int:
            cnt = 0
            for kw in keywords:
                if len(kw) <= 3:
                    if re.search(r"\b" + re.escape(kw) + r"\b", q_lower):
                        cnt += 1
                else:
                    if kw in q_lower:
                        cnt += 1
            return cnt

        scores = {
            "Power Trader": count_matches(trader_keywords),
            "Municipal Co-op": count_matches(coop_keywords),
            "State Regulator": count_matches(regulator_keywords),
            "Public / Media": count_matches(public_keywords),
        }

        best_persona, best_score = max(scores.items(), key=lambda x: x[1])
        if best_score >= 1 and best_persona != current_persona:
            reasons = {
                "Power Trader": "Query contains arbitrage spreads, LMP volatility, or congestion terms",
                "Municipal Co-op": "Query focuses on baseload hedging, capacity reserve margins, or co-op procurement",
                "State Regulator": "Query includes regulatory filings, CONE, tariff compliance, or transmission planning",
                "Public / Media": "Query uses conversational, educational, or clean energy terminology",
            }
            return best_persona, reasons[best_persona]

        return None, None

    def _execute_search(self, query: str, persona: str = "Power Trader") -> SearchResponse:
        q_norm = normalize(query)

        # 1. Check if user explicitly asked for an acronym / definition ("what is", "explain", "formula", or exact acronym)
        is_definitional = any(term in q_norm for term in ["what is", "define", "definition", "explain", "formula", "meaning", "acronym"])
        if is_definitional:
            glossary_match = self._match_glossary(q_norm)
            if glossary_match:
                return self._build_glossary_response(query, glossary_match, persona)

        # 2. Check for exact standalone Glossary Acronym match (e.g. user typed "LMP", "CONE", "PRA", "LRTP", "COD")
        if q_norm.upper() in self.dm.glossary:
            entry = self.dm.glossary[q_norm.upper()]
            return self._build_glossary_response(query, {"acronym": q_norm.upper(), **entry}, persona)

        # 3. Check for Specific Hub Intent (e.g. "Indiana Hub LMP", "Michigan Hub")
        # 3. Check for Footprint / Manitoba / Canada / Who is MISO
        if any(term in q_norm for term in ["manitoba", "canada", "footprint", "territory", "who is miso", "about miso", "states served"]):
            return self._build_footprint_response(query, persona)

        # 4. Check for Price Spike Intent
        if any(term in q_norm for term in ["spike", "price surge", "why did prices", "price jump", "high lmp", "why is power expensive", "price spike"]):
            return self._build_price_spike_response(query, persona)

        # 5. Check for Energy Storage / Battery Intent
        if any(term in q_norm for term in ["storage", "battery", "batteries", "bess", "pumped hydro", "pumped storage"]):
            return self._build_storage_response(query, persona)

        # 6. Check for Specific Hub Intent (e.g. "Indiana Hub LMP", "Michigan Hub")
        hub_match = self._match_hub(q_norm)
        if hub_match:
            return self._build_hub_response(query, hub_match, persona)

        # 4. Check for Fuel Mix / Generation / Peak Intent
        # 7. Check for Fuel Mix / Generation / Peak Intent
        if any(term in q_norm for term in ["fuel", "solar", "wind", "coal", "gas", "nuclear", "peak", "demand", "mix", "generation"]):
            return self._build_fuel_response(query, q_norm, persona)

        # 5. Check for Transmission / MTEP / LRTP / Seam Intent
        # 8. Check for Transmission / MTEP / LRTP / Seam Intent
        if any(term in q_norm for term in ["mtep", "lrtp", "jtiq", "transmission", "lines", "miles", "grid expansion"]):
            return self._build_transmission_response(query, q_norm, persona)

        # 6. Check for partial Glossary / Acronym match
        # 9. Check for partial Glossary / Acronym match
        glossary_match = self._match_glossary(q_norm)
        if glossary_match:
            return self._build_glossary_response(query, glossary_match, persona)

        # 7. Semantic Intent Classification & Out-of-Scope Domain Check (Issue #11)
        # 10. Semantic Intent Classification & Out-of-Scope Domain Check (Issue #11)
        classification = llm_service.classify_intent_and_entities(query)
        if classification.get("intent") == "out_of_scope":
            return self._build_out_of_scope_response(query, persona)
        elif classification.get("intent") == "hub_pricing" and classification.get("hub_id"):
            return self._build_hub_response(query, classification["hub_id"], persona)
        elif classification.get("intent") == "fuel_mix_peak":
            return self._build_fuel_response(query, q_norm, persona)
        elif classification.get("intent") == "transmission_planning":
            return self._build_transmission_response(query, q_norm, persona)

        # 8. Offline Domain Check: If query contains no energy/MISO terms and is multi-word, guide user
        # 11. General questions / conversational prompts with energy grounding
        if any(term in q_norm for term in ["why", "how", "what", "can", "tell me", "explain", "who", "when", "describe"]):
            return self._build_general_question_response(query, persona)

        # 12. Offline Domain Check: If query contains no energy/MISO terms and is multi-word, guide user
        from llm_service import MISO_DOMAIN_TERMS
        tokens = set(re.findall(r"\w+", q_norm))
        glossary_keys = {k.lower() for k in self.dm.glossary.keys()}
        all_valid_terms = MISO_DOMAIN_TERMS | glossary_keys
        if len(tokens) >= 2 and not (tokens & all_valid_terms):
            return self._build_out_of_scope_response(query, persona)

        # 9. Default / Fallback: Indiana Hub Market Pricing
        # 13. Default / Fallback: Indiana Hub Market Pricing
        return self._build_hub_response(query, "INDIANA.HUB", persona, is_fallback=True)

